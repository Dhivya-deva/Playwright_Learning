//pre-increment,post-increment,pre-decrement,post-decrement

//post-increment (x++)
let x=50
console.log(x++) 
console.log(x)

//pre-increment (++y)
let y=30
console.log(++y)

//pre-decrement (--a)
let a=90
console.log(--a) 

//post-decrement (b--)
let b=30
console.log(b--) 
console.log(b)